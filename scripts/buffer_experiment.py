"""Buffer-size experiment (Dragon Book 3.2: trade-offs of the buffer size).

Lexes one large generated input with different buffer half sizes N and records
the number of half reloads and the lexing time. Writes the result to
docs/buffer_experiment.md. Every number in that file comes from this script.

Run:  .venv/bin/python scripts/buffer_experiment.py
"""

import platform
import statistics
import sys
import time
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from minilang.lexer import Lexer  # noqa: E402
from minilang.report import render_table  # noqa: E402

SIZES = [8, 16, 64, 256, 1024, 4096, 16384]
REPEATS = 5
COPIES = 400


def make_input() -> str:
    parts = [(ROOT / "examples" / f"{n}.mini").read_text() for n in ("factorial", "scopes")]
    return "\n".join(parts) * COPIES


def cpu_name() -> str:
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or "unknown"


def longest_lexeme(text: str) -> tuple[int, str]:
    tokens = Lexer(text).tokenize()
    tok = max(tokens, key=lambda t: len(t.lexeme))
    return len(tok.lexeme), tok.lexeme


def smallest_working_size(text: str) -> int:
    n = 1
    while True:
        lexer = Lexer(text, half_size=n)
        lexer.tokenize()
        if not lexer.errors:
            return n
        n += 1


def run(text: str, n: int) -> tuple[int, int, float]:
    times = []
    for _ in range(REPEATS):
        lexer = Lexer(text, half_size=n)
        start = time.perf_counter()
        tokens = lexer.tokenize()
        times.append(time.perf_counter() - start)
        assert not lexer.errors, lexer.errors.format()
    return len(tokens), lexer.buf.reloads, statistics.median(times)


def main() -> None:
    text = make_input()
    rows = []
    reference = None
    for n in SIZES:
        count, reloads, seconds = run(text, n)
        if reference is None:
            reference = count
        assert count == reference, "token count changed with the buffer size"
        rows.append([n, reloads, f"{seconds * 1000:.1f}", f"{len(text) / seconds / 1e6:.2f}"])

    longest, longest_text = longest_lexeme(text)
    smallest = smallest_working_size(text)
    table = render_table(
        ["Half size N", "Half reloads", "Median time (ms)", "M chars/s"], rows, markdown=True)
    out = f"""# Buffer-size experiment (Dragon Book 3.2)

Generated by `scripts/buffer_experiment.py` on {date.today().isoformat()}.

- Input: `examples/factorial.mini` + `examples/scopes.mini`, repeated {COPIES} times
  ({len(text):,} characters, {reference:,} tokens)
- Each size was run {REPEATS} times; the median time is shown.
- Python {platform.python_version()}, {platform.system()} {platform.machine()},
  CPU: {cpu_name()}
- Longest lexeme in the input: {longest} characters ({longest_text!r});
  smallest half size that lexes the input without error: N = {smallest}

{table}

## Reading the table

- Reloads fall in proportion to 1/N: each reload reads N characters.
- A lexeme must fit in one half (Section 3.2.1); the lookahead character may sit
  in the other half. The smallest working N above was found by trying
  N = 1, 2, 3, ... on this input.
- Compare the reload column with the time column: in this Python implementation
  the per-character work dominates, so the time changes much less than the
  reload count.
- Explanation, not measured here: in a C scanner reading from disk each reload
  is a system call, which is why real scanners use N = 4096 (a disk block) or more.
"""
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "buffer_experiment.md").write_text(out, encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
